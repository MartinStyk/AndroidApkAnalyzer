import androidx.compose.ui.graphics.vector.ImageVector

fun permissionIcon(name: String, groupName: String?): ImageVector = permissionIcons[name] ?: groupIcons[groupName] ?: ApkAnalyzerIcons.Permissions

fun requirementIcon(name: String?): ImageVector = when (name) {
    null -> ApkAnalyzerIcons.Graphics
    else -> requirementIcons[name] ?: ApkAnalyzerIcons.Android
}

